// ignore_for_file: avoid_print
// Generates a realistic large TEST shop database directly in Hive (same box
// files and record shapes the app uses), deterministically (Random(42)).
// Usage: dart run tool/perf/seed.dart <new-empty-dir> <products> <sales> <serials>
// Never point it at the real data folder: it only writes into a folder that
// is empty or was created by this tool before.
import 'dart:io';
import 'dart:math';

import 'package:al_aqsa_cctv/core/ids.dart';
import 'package:al_aqsa_cctv/data/store/data_store.dart';
import 'package:hive_ce/hive.dart';

late Random rnd;
int _id = 0;
String nid() => 'b${(_id++).toRadixString(36).padLeft(9, '0')}';
String iso(DateTime d) => d.toIso8601String();

Future<void> main(List<String> a) async {
  final dir = a[0];
  final nProducts = int.parse(a[1]), nSales = int.parse(a[2]), nSerials = int.parse(a[3]);
  rnd = Random(42);
  final d = Directory(dir);
  final marker = File('$dir/.aqsa_perf_dataset');
  if (d.existsSync() && d.listSync().isNotEmpty && !marker.existsSync()) {
    print('Refusing to write: "$dir" is not empty and was not made by this tool.');
    exit(2);
  }
  if (d.existsSync()) d.deleteSync(recursive: true);
  d.createSync(recursive: true);
  marker.writeAsStringSync('test dataset generated by tool/perf/seed.dart');
  Hive.init(dir);
  final boxes = <String, Map<String, Map>>{for (final b in Boxes.all) b: {}};
  final start = DateTime(2024, 11, 1);
  final owner = nid();
  boxes[Boxes.users]![owner] = {'id': owner, 'username': 'owner', 'displayName': 'Owner', 'passwordHash': 'x', 'role': 'owner', 'active': true, 'employeeId': null, 'mustChangePassword': false, 'createdAt': iso(start)};
  boxes[Boxes.meta]!['schema'] = {'version': 2};
  // categories
  final cats = [for (var i = 0; i < 30; i++) nid()];
  for (var i = 0; i < cats.length; i++) {
    boxes[Boxes.categories]![cats[i]] = {'id': cats[i], 'name': 'Category ${i + 1}', 'active': true};
  }
  const brands = ['Hikvision', 'Dahua', 'Uniview', 'Seagate', 'WD', 'TP-Link', 'Ezviz', 'Imou', 'Generic'];
  // suppliers / customers
  final suppliers = [for (var i = 0; i < 200; i++) nid()];
  for (var i = 0; i < suppliers.length; i++) {
    boxes[Boxes.suppliers]![suppliers[i]] = {'id': suppliers[i], 'kind': 'supplier', 'name': 'Supplier ${i + 1} Trading Co', 'company': '', 'contactPerson': '', 'phone': '0300${100000 + i}', 'address': 'Rawalpindi', 'email': '', 'openingBalance': 0, 'balance': rnd.nextInt(5000000), 'notes': '', 'active': true, 'createdAt': iso(start)};
  }
  final customers = [for (var i = 0; i < 2000; i++) nid()];
  for (var i = 0; i < customers.length; i++) {
    boxes[Boxes.customers]![customers[i]] = {'id': customers[i], 'kind': 'customer', 'name': 'Customer ${i + 1} ${['Traders', 'Electronics', 'Security', 'Builders'][i % 4]}', 'company': '', 'contactPerson': '', 'phone': '0311${100000 + i}', 'address': 'Islamabad', 'email': '', 'openingBalance': 0, 'balance': 0, 'notes': '', 'active': true, 'createdAt': iso(start)};
  }
  // products + barcodes + cost layers + purchase movements
  final products = <String>[];
  final serialProducts = <String>[];
  final price = <String, int>{}, cost = <String, int>{}, names = <String, String>{};
  for (var i = 0; i < nProducts; i++) {
    final id = nid();
    products.add(id);
    final serial = i % 5 == 0;
    if (serial) serialProducts.add(id);
    final c = (500 + rnd.nextInt(60000)) * 100;
    final p = (c * (1.2 + rnd.nextDouble() * 0.4)).round();
    price[id] = p;
    cost[id] = c;
    final code = 'AQ${(i + 1).toString().padLeft(8, '0')}';
    final brand = brands[i % brands.length];
    final name = '$brand ${['4MP Dome Camera', '8CH NVR', '2TB Surveillance HDD', 'PoE Switch 8 Port', 'Cat6 Cable', 'Bullet Camera 5MP', 'DVR 16CH', 'Power Supply 12V'][i % 8]} Model ${i + 1}';
    names[id] = name;
    final qty = (5 + rnd.nextInt(200)) * 1000;
    boxes[Boxes.products]![id] = {'id': id, 'name': name, 'sku': code, 'categoryId': cats[i % cats.length], 'brand': brand, 'model': 'M${i + 1}', 'description': '', 'purchasePrice': c, 'sellingPrice': p, 'wholesalePrice': null, 'stockQty': qty, 'issuedQty': 0, 'damagedQty': 0, 'inspectionQty': 0, 'repairableQty': 0, 'minStock': 10000, 'unit': 'pcs', 'allowDecimal': false, 'internalCode': code, 'barcodes': [code, '89${(1000000000 + i)}'], 'requiresSerial': serial, 'warrantyMonths': 12, 'imagePath': null, 'archived': false, 'createdAt': iso(start), 'updatedAt': iso(start)};
    for (final bc in [code, '89${(1000000000 + i)}']) {
      boxes[Boxes.barcodes]![indexKey(normalizeCode(bc))] = {'productId': id, 'code': normalizeCode(bc)};
    }
    for (var l = 0; l < 2; l++) {
      final lid = nid();
      final d = start.add(Duration(days: rnd.nextInt(700)));
      boxes[Boxes.costLayers]![lid] = {'id': lid, 'productId': id, 'sourceType': 'purchase', 'sourceId': 'seed', 'date': iso(d), 'qtyIn': qty, 'qtyRemaining': qty ~/ 2, 'unitCost': c};
      final mid = nid();
      boxes[Boxes.stockMovements]![mid] = {'id': mid, 'productId': id, 'at': iso(d), 'type': 'purchase', 'bucket': 'available', 'qty': qty ~/ 2, 'before': 0, 'after': qty ~/ 2, 'value': c * qty ~/ 2000, 'refType': 'purchase', 'refId': 'seed', 'reason': 'PUR', 'userId': owner};
    }
  }
  // serials
  const statuses = ['inStock', 'inStock', 'inStock', 'inStock', 'inStock', 'inStock', 'sold', 'sold', 'sold', 'issuedToTechnician'];
  for (var i = 0; i < nSerials; i++) {
    final pid = serialProducts[i % serialProducts.length];
    final sn = 'SN${(i + 1).toString().padLeft(9, '0')}';
    final brandKey = (boxes[Boxes.products]![pid]!['brand'] as String).toUpperCase();
    final key = '$brandKey|$sn';
    final st = statuses[i % statuses.length];
    final pd = start.add(Duration(days: rnd.nextInt(700)));
    boxes[Boxes.serials]![key] = {'key': key, 'serial': sn, 'brandKey': brandKey, 'productId': pid, 'supplierId': suppliers[i % suppliers.length], 'purchaseId': 'seed', 'purchaseDate': iso(pd), 'cost': cost[pid], 'status': st, 'technicianId': null, 'customerId': st == 'sold' ? customers[i % customers.length] : null, 'saleId': null, 'warrantyStart': st == 'sold' ? iso(pd) : null, 'warrantyExpiry': st == 'sold' ? iso(pd.add(const Duration(days: 365))) : null, 'duplicateApprovedBy': null, 'history': [{'at': iso(pd), 'status': 'inStock', 'note': 'Purchased', 'refType': 'purchase', 'refId': 'seed', 'userId': owner}]};
    boxes[Boxes.serialIndex]![normalizeCode(sn)] = {'keys': [key]};
  }
  // purchases
  for (var i = 0; i < 2000; i++) {
    final id = nid();
    final d = start.add(Duration(days: rnd.nextInt(745)));
    final items = [for (var k = 0; k < 1 + rnd.nextInt(4); k++) products[rnd.nextInt(products.length)]];
    var total = 0;
    final its = [for (final pid in items) {'productId': pid, 'name': names[pid], 'qty': 10000, 'unitCost': cost[pid], 'discount': 0, 'tax': 0, 'serials': <String>[], 'returnedQty': 0}];
    for (final pid in items) {
      total += cost[pid]! * 10;
    }
    boxes[Boxes.purchases]![id] = {'id': id, 'number': 'PUR-${(i + 1).toString().padLeft(6, '0')}', 'supplierId': suppliers[i % suppliers.length], 'supplierInvoiceNo': '', 'date': iso(d), 'items': its, 'paidAtPurchase': total, 'method': 'cash', 'notes': '', 'status': 'completed', 'createdBy': owner, 'createdAt': iso(d), 'cancelReason': '', 'total': total};
  }
  // sales (+ movements, ledger, audit). 40% of credit sales go to 50 "big" customers.
  final bal = <String, int>{};
  for (var i = 0; i < nSales; i++) {
    final id = nid();
    final d = start.add(Duration(minutes: (i * (745 * 24 * 60) / nSales).round()));
    final cust = rnd.nextInt(10) < 3 ? (rnd.nextInt(10) < 4 ? customers[rnd.nextInt(50)] : customers[rnd.nextInt(customers.length)]) : null;
    final items = <Map<String, dynamic>>[];
    var total = 0;
    for (var k = 0; k < 1 + rnd.nextInt(3); k++) {
      final pid = products[rnd.nextInt(products.length)];
      final q = 1 + rnd.nextInt(3);
      items.add({'productId': pid, 'name': names[pid], 'qty': q * 1000, 'unitPrice': price[pid], 'discount': 0, 'serials': <String>[], 'cogs': cost[pid]! * q, 'returnedQty': 0, 'techUsageId': null});
      total += price[pid]! * q;
      final mid = nid();
      boxes[Boxes.stockMovements]![mid] = {'id': mid, 'productId': pid, 'at': iso(d), 'type': 'sale', 'bucket': 'available', 'qty': -q * 1000, 'before': 100000, 'after': 100000 - q * 1000, 'value': cost[pid]! * q, 'refType': 'sale', 'refId': id, 'reason': 'INV', 'userId': owner};
    }
    final paid = cust == null ? total : (total * rnd.nextInt(80) ~/ 100);
    final number = 'INV-${(i + 1).toString().padLeft(6, '0')}';
    boxes[Boxes.sales]![id] = {'id': id, 'number': number, 'customerId': cust, 'customerName': cust == null ? 'Walk-in Customer' : boxes[Boxes.customers]![cust]!['name'], 'date': iso(d), 'items': items, 'invoiceDiscount': 0, 'paidAtSale': paid, 'method': 'cash', 'notes': '', 'status': 'completed', 'createdBy': owner, 'createdAt': iso(d), 'cancelReason': '', 'quotationId': null, 'creditApprovedBy': cust != null && paid < total ? owner : null, 'warrantyFromInstallation': false};
    if (cust != null) {
      final lid = nid();
      boxes[Boxes.ledger]![lid] = {'id': lid, 'partyKind': 'customer', 'partyId': cust, 'at': iso(d), 'type': 'sale', 'debit': total, 'credit': 0, 'refType': 'sale', 'refId': id, 'refNumber': number, 'note': 'Sale', 'userId': owner};
      bal[cust] = (bal[cust] ?? 0) + total;
      if (paid > 0) {
        final pid = nid(), l2 = nid();
        boxes[Boxes.payments]![pid] = {'id': pid, 'number': 'PAY-${pid.substring(3)}', 'partyKind': 'customer', 'partyId': cust, 'at': iso(d), 'amount': paid, 'method': 'cash', 'direction': 'received', 'refType': 'sale', 'refId': id, 'note': '', 'userId': owner, 'voided': false, 'voidReason': ''};
        boxes[Boxes.ledger]![l2] = {'id': l2, 'partyKind': 'customer', 'partyId': cust, 'at': iso(d), 'type': 'payment', 'debit': 0, 'credit': paid, 'refType': 'payment', 'refId': pid, 'refNumber': 'PAY', 'note': 'Payment', 'userId': owner};
        bal[cust] = bal[cust]! - paid;
      }
    }
    final aid = nid();
    boxes[Boxes.auditLogs]![aid] = {'id': aid, 'at': iso(d), 'userId': owner, 'action': 'complete', 'entity': 'sale', 'entityId': id, 'details': number};
  }
  bal.forEach((c, b) => boxes[Boxes.customers]![c]!['balance'] = b);
  boxes[Boxes.meta]!['seq_invoice'] = {'value': nSales};
  boxes[Boxes.meta]!['seq_purchase'] = {'value': 2000};
  boxes[Boxes.settings]!['app'] = {'businessName': 'AL AQSA CCTV', 'backupDirectory': ''};
  // write boxes
  var total = 0;
  for (final b in Boxes.all) {
    final box = await Hive.openBox<Map>(b);
    await box.putAll(boxes[b]!);
    await box.flush();
    total += boxes[b]!.length;
  }
  await Hive.openBox<Map>('_journal');
  await Hive.close();
  final size = Directory(dir).listSync().whereType<File>().fold<int>(0, (s, f) => s + f.lengthSync());
  print('seeded $total records, ${(size / 1048576).toStringAsFixed(1)} MB on disk: products=$nProducts sales=$nSales serials=$nSerials '
      'ledger=${boxes[Boxes.ledger]!.length} payments=${boxes[Boxes.payments]!.length} movements=${boxes[Boxes.stockMovements]!.length}');
}
